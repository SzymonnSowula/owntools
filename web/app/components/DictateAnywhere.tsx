function Mark({ brand, size = 17 }: { brand: Brand; size?: number }) {
  /* A brand whose mark is pure black disappears on the night panel. Those
     follow the ink token instead, which is black by day and white by night —
     the same swap their own dark-mode assets make. */
  const monochrome = brand.hex.toLowerCase() === "#000000";
  return (
    <svg
      role="img"
      aria-label={brand.name}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="currentColor"
      className={monochrome ? "text-ink" : undefined}
      style={monochrome ? undefined : { color: brand.hex }}
    >
      <path d={brand.path} />
    </svg>
  );
}

