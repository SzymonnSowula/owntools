/**
 * Recorded samples the packs can lay under or instead of a synthesised
 * layer. Stored as base64 PCM16 so the sound stays a pure function of the
 * code — no fetch, no asset pipeline, tests hear the same bytes — and small
 * enough to keep in source (a mouse click is a few thousand samples).
 *
 * `mouseClick`: a real mouse click, HD recording supplied on 2026-09-07
 * (Downloads/Mouse_Click_-_Sound_Effect_HD.wav), stereo folded to mono,
 * trimmed to the sound (0.156 s), normalised to 0.9. It holds both halves of
 * a click: the press at 0 and the release at `MOUSE_CLICK_SPLIT` seconds,
 * which is where a recipe slices it in two so the release can play when the
 * button actually came up.
 *
 * `keyboard`: six keystrokes off one mechanical board, cut from the 50 s
 * recording supplied on 2026-09-08 (freesound_community-mechanical-keyboard-
 * 27060.mp3). `KEYBOARD_CUTS` says where each one sits. The recording never
 * says which key was struck, so they were chosen by measurement instead of
 * guesswork: the deepest, longest tap in the take (centroid 1.7 kHz, 90 ms of
 * ring) is the space bar, the snappiest (2.8 kHz, 24 ms) is backspace, and the
 * three ordinary keys are far enough apart in brightness that a sentence does
 * not sound like one sample on repeat. Stored at 24 kHz because the source has
 * no energy at all above 12 kHz — half the bytes for nothing lost.
 */

