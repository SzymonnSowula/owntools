function decodePcm16(base64: string): Float32Array {
  const bin = atob(base64);
  const out = new Float32Array(bin.length >> 1);
  for (let i = 0; i < out.length; i++) {
    const lo = bin.charCodeAt(i * 2);
    const hi = bin.charCodeAt(i * 2 + 1);
    let v = lo | (hi << 8);
    if (v >= 0x8000) v -= 0x10000;
    out[i] = v / 32768;
  }
  return out;
}

const cache = new Map<SampleId, Sample>();

export function sample(id: SampleId): Sample {
  let hit = cache.get(id);
  if (!hit) {
    hit = { sampleRate: 48000, data: decodePcm16(MOUSE_CLICK_PCM) };
    cache.set(id, hit);
  }
  return hit;
}
